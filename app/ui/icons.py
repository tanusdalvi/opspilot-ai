def icon_svg(name: str, size: int = 18, stroke_width: float = 2.0,
             class_name: str | None = None) -> str:
    """Return an inline ``<svg>`` string for the given icon name."""
    body = _ICONS.get(name, _ICONS["info"])
    classes = f' class="{class_name}"' if class_name else ""
    return (
        f'<svg{classes} xmlns="http://www.w3.org/2000/svg" width="{size}" '
        f'height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="{stroke_width}" stroke-linecap="round" '
        f'stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


def icon_html(name: str, size: int = 18, stroke_width: float = 2.0,
              class_name: str | None = None) -> str:
    """Return the icon wrapped in the styled ``ops-icon`` span."""
    extra = f" {class_name}" if class_name else ""
    svg = icon_svg(name, size=size, stroke_width=stroke_width)
    return f'<span class="ops-icon{extra}">{svg}</span>'


def escape_label(text: object) -> str:
    """Escape untrusted-looking text before embedding it in HTML."""
    return html.escape(str(text))
